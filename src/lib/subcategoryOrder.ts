/** Subcategories in their fixed order, then any not listed there (in data
 * order), so a new subcategory still shows instead of being hidden. */
export function orderSubcategories(order: string[] | undefined, present: string[]): string[] {
  if (!order) return present;
  return [...order, ...present.filter((s) => !order.includes(s))];
}

